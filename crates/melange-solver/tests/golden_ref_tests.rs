/// Small-signal companion (review-round-2 H3): 40 mV drive keeps the whole
/// waveform inside the ±10 V rails (peak 2.38 V), so every sample carries
/// plate-current information and the Koren transfer curve is actually gated.
///
/// Reference: ngspice-42 B-source Koren twin (independent of melange) —
/// `Ip = 2·pwr(uramp(E1),EX)/KG1` — regenerated by
/// `tests/golden/ngspice_ref/regen_ngspice_goldens.py`. DC OP cross-check:
/// plate 170.1017 V / cathode 1.1985 V on BOTH engines (4+ decimals).
///
/// Tolerance: measured 2026-07-21 max |melange − ngspice| = 2.54e-3 V
/// (0.105% normalized rms). 6e-3 = 2.4× measured margin. A ×2-class
/// plate-current error (the July 2026 Koren dispute) moves the peak by
/// >1 V and fails by >400×.
#[test]
fn golden_triode_cc_small_sine_500hz() {
    let c = config(TRIODE_CC);
    let circuit = support::build_circuit(TRIODE_CC, &c, "g_triode_small");
    let output = support::run_sine(&circuit, 500.0, 0.04, 960, SR);
    support::assert_matches_golden(&output, "triode_cc_small_sine_500hz.json", 6e-3);

    // Pinned stage gain (review-round-2 H4 tripwire, triode family).
    // Settled-window RMS gain: samples 480..960 = exactly 5 cycles of 500 Hz.
    // Measured 2026-07-21: melange +35.3573 dB, ngspice B-source reference
    // +35.3563 dB (Δ = 0.0010 dB). ±0.2 dB gate = 200× the engine delta;
    // a ×2 plate-current error moves this by ≈ 6 dB.
    //
    // RE-PIN PROTOCOL: if this literal ever needs to move, produce the
    // OOMOX_CONTRACT.md §7 downstream impact list FIRST (per-stage deltas
    // multiply through cascades: series-of-tubes ×64, uniquorn ×16) and
    // re-derive the ngspice reference — do not re-pin from melange output.
    let settled = &output[480..];
    let out_rms = (settled.iter().map(|v| v * v).sum::<f64>() / settled.len() as f64).sqrt();
    let in_rms = 0.04 / std::f64::consts::SQRT_2;
    let gain_db = 20.0 * (out_rms / in_rms).log10();
    assert!(
        (gain_db - 35.3573).abs() < 0.2,
        "triode CC stage gain drifted: measured {gain_db:.4} dB vs pinned +35.3573 dB \
         (ngspice B-source reference: +35.3563 dB, measured 2026-07-21)"
    );
}

