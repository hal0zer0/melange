//! Golden reference tests: codegen output vs recorded reference output.
//!
//! These tests verify that the codegen pipeline produces output matching
//! recorded reference waveforms within tolerance.
//!
//! Reference provenance is mixed and each file's `generator` field is
//! authoritative:
//! - most goldens were recorded by `record_golden_refs.rs` from the
//!   (since deleted) runtime solver;
//! - `opamp_inverting_sine_1k.json`, `opamp_noninverting_sine_1k.json`
//!   and `triode_cc_small_sine_500hz.json` hold NGSPICE output
//!   (review-round-2 H1 fix: goldens re-recorded from melange's own
//!   codegen cannot arbitrate a solver-math dispute). They are
//!   regenerated by `tests/golden/ngspice_ref/regen_ngspice_goldens.py`
//!   from the deck templates in the same directory — never from melange.
//! - `triode_cc_sine_500hz.json` (0.5 V drive, 742/960 samples at the
//!   ±10 V output clamp) intentionally remains a codegen self-recording:
//!   the clamp is a melange codegen feature with no ngspice counterpart,
//!   so this golden gates the clamp and sample-level drift only. The
//!   tube TRANSFER CURVE is gated by the ngspice-referenced small-signal
//!   companion below.

